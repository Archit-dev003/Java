public class P02_Literal {
    public static void main(String[] args) {
        
        int n = 10;
        double a = 12e9; //varibale = literal
        char c = 'a';
        boolean value = true;
        float f = 8.9f;

        System.out.println("The value of n is: "+n);
        System.out.println("The exponential value of a is: "+a);
        System.out.println("The character held in c is: "+c);
        System.out.println("Is java object oriented?: "+value);
        System.out.println("Value of f is: "+f);
    }
}
